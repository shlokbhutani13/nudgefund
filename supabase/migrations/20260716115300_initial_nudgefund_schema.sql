create extension if not exists pgcrypto;
create schema if not exists private;

revoke all on schema private from public, anon, authenticated;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default ''
    check (char_length(display_name) <= 80),
  currency_code text not null default 'USD'
    check (currency_code ~ '^[A-Z]{3}$'),
  monthly_savings_goal numeric(12, 2) not null default 0
    check (monthly_savings_goal >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.purchase_decisions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  item_name text not null
    check (char_length(item_name) between 1 and 120),
  planned_amount numeric(12, 2) not null
    check (planned_amount > 0 and planned_amount <= 100000000),
  category text not null
    check (char_length(category) between 1 and 50),
  questions jsonb not null
    check (
      jsonb_typeof(questions) = 'array'
      and jsonb_array_length(questions) = 3
    ),
  answers jsonb not null
    check (
      jsonb_typeof(answers) = 'array'
      and jsonb_array_length(answers) = 3
    ),
  verdict text not null
    check (verdict in ('positive', 'neutral', 'negative')),
  recommendation text not null
    check (char_length(recommendation) between 1 and 1000),
  final_item_name text not null
    check (char_length(final_item_name) between 1 and 120),
  final_amount numeric(12, 2) not null
    check (final_amount >= 0 and final_amount <= 100000000),
  amount_redirected numeric(12, 2)
    generated always as (
      greatest(planned_amount - final_amount, 0)
    ) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index purchase_decisions_user_created_idx
  on public.purchase_decisions(user_id, created_at desc);

create table private.ai_usage_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  request_kind text not null
    check (
      request_kind in ('questions', 'verdict', 'monthly_report')
    ),
  created_at timestamptz not null default now()
);

create index ai_usage_events_user_created_idx
  on private.ai_usage_events(user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.purchase_decisions enable row level security;
alter table private.ai_usage_events enable row level security;

revoke all on public.profiles from public, anon, authenticated;
revoke all on public.purchase_decisions from public, anon, authenticated;
revoke all on private.ai_usage_events from public, anon, authenticated;

grant usage on schema public to authenticated;
