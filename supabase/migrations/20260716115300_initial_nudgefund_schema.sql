create or replace function public.consume_ai_quota(
  p_request_kind text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_user_id uuid := (select auth.uid());
  recent_count integer;
begin
  if caller_user_id is null then
    raise exception 'authentication required'
      using errcode = '42501';
  end if;

  if p_request_kind not in (
    'questions',
    'verdict',
    'monthly_report'
  ) then
    raise exception 'invalid request kind'
      using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(caller_user_id::text, 0)
  );

  select count(*)
  into recent_count
  from private.ai_usage_events
  where user_id = caller_user_id
    and created_at >= pg_catalog.now() - interval '1 hour';

  if recent_count >= 12 then
    return false;
  end if;

  insert into private.ai_usage_events(
    user_id,
    request_kind
  )
  values (
    caller_user_id,
    p_request_kind
  );

  return true;
end;
$$;

revoke all on function public.consume_ai_quota(text)
  from public, anon, authenticated;
grant execute on function public.consume_ai_quota(text)
  to authenticated;
